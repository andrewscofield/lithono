import { globSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { create as createManifest } from '@custom-elements-manifest/analyzer/index.js';
import { litPlugin } from '@custom-elements-manifest/analyzer/src/features/framework-plugins/lit/lit.js';
import { ELEMENT_GLOBS, tagFromModuleId } from '../element-id.ts';

const require = createRequire(import.meta.url);
function loadTypescript(): {
  createSourceFile(file: string, text: string, target: number, setParentNodes: boolean): unknown;
  ScriptTarget: { Latest: number };
  isClassDeclaration(node: unknown): node is { name?: { getText(): string }; modifiers?: Array<{ kind: number }> };
  SyntaxKind: { DefaultKeyword: number; ExportKeyword: number };
} | null {
  const candidates = ['typescript-parser', 'typescript', '@custom-elements-manifest/analyzer/node_modules/typescript'];
  for (const spec of candidates) {
    try {
      const mod = require(spec) as Record<string, unknown>;
      const loaded = (typeof mod.createSourceFile === 'function' ? mod : mod.default) as
        | Record<string, unknown>
        | undefined;
      if (loaded && typeof loaded.createSourceFile === 'function') {
        return loaded as never;
      }
    } catch {
      // try next
    }
  }
  return null;
}

const MANIFEST_FILE = 'custom-elements.json';
const HTML_DATA_FILE = '.vscode/lithono.html-data.json';
const TAG_MAP_FILE = 'src/framework/generated/elements.d.ts';

interface CemPackage {
  schemaVersion: string;
  readme: string;
  modules: Array<{
    path?: string;
    declarations?: Array<{
      kind?: string;
      customElement?: boolean;
      name?: string;
      tagName?: string;
      description?: string;
      attributes?: Array<{ name?: string; type?: { text?: string }; default?: string }>;
    }>;
  }>;
}

function listElementFiles(root: string): string[] {
  const files = new Set<string>();
  for (const pattern of ELEMENT_GLOBS) {
    for (const file of globSync(pattern, { cwd: root })) {
      const posix = file.replaceAll('\\', '/');
      if (posix.endsWith('.ts') && !posix.endsWith('.d.ts')) files.add(posix);
    }
  }
  return [...files].sort();
}

function filenameTagPlugin() {
  return {
    name: 'lithono-filename-tag',
    analyzePhase({ ts: tsv, node, moduleDoc }: {
      ts: {
        isClassDeclaration(node: unknown): boolean;
        SyntaxKind: { DefaultKeyword: number; ExportKeyword: number };
      };
      node: {
        name?: { getText(): string };
        modifiers?: Array<{ kind: number }>;
      };
      moduleDoc: { path?: string; declarations?: Array<{ name?: string; tagName?: string; customElement?: boolean }> };
    }) {
      if (!tsv.isClassDeclaration(node) || !node.name) return;
      const isDefault = node.modifiers?.some((mod) => mod.kind === tsv.SyntaxKind.DefaultKeyword);
      if (!isDefault && !node.modifiers?.some((mod) => mod.kind === tsv.SyntaxKind.ExportKeyword)) return;
      const tag = tagFromModuleId(moduleDoc.path ?? '');
      if (!tag.includes('-')) return;
      const decl = moduleDoc.declarations?.find((item: { name?: string }) => item.name === node.name?.getText());
      if (decl && !decl.tagName) {
        decl.tagName = tag;
        decl.customElement = true;
      }
    },
  };
}

export function buildCustomElementsManifest(root: string): CemPackage {
  const compiler = loadTypescript();
  if (!compiler) {
    return { schemaVersion: '1.0.0', readme: 'CEM skipped: TypeScript compiler API unavailable.', modules: [] };
  }
  const files = listElementFiles(root);
  const modules = files.map((file) =>
    compiler.createSourceFile(
      file,
      readFileSync(join(root, file), 'utf8'),
      compiler.ScriptTarget?.Latest ?? 99,
      true
    )
  );
  const manifest = createManifest({
    modules,
    plugins: [...litPlugin(), filenameTagPlugin()],
    context: { dev: false },
  }) as CemPackage;
  manifest.readme = 'Generated by Lithono via @custom-elements-manifest/analyzer + litPlugin.';
  return manifest;
}

export function buildVscodeHtmlData(manifest: CemPackage) {
  const tags: unknown[] = [
    {
      name: 'lithono-if',
      description: 'Compile-only: becomes `${when ? html`…` : nothing}`. Never a custom element.',
      attributes: [{ name: 'when', description: 'JavaScript expression. Truthy keeps the inner HTML.' }],
    },
    {
      name: 'lithono-each',
      description: 'Compile-only: becomes `.map()` or `repeat()`. Never a custom element.',
      attributes: [
        { name: 'items', description: 'Array expression to iterate.' },
        { name: 'as', description: 'Loop variable name (default: item).' },
        { name: 'key', description: 'Item property used as the repeat key.' },
      ],
    },
  ];
  for (const module of manifest.modules) {
    for (const declaration of module.declarations ?? []) {
      if (!declaration.tagName) continue;
      tags.push({
        name: declaration.tagName,
        description: declaration.description ?? `Custom element \`<${declaration.tagName}>\`.`,
        attributes: (declaration.attributes ?? []).map((attr) => ({
          name: attr.name,
          description: attr.type?.text ? `Type: \`${attr.type.text}\`` : undefined,
        })),
        references: [
          {
            name: declaration.name ?? declaration.tagName,
            url: `./${module.path}`,
          },
        ],
      });
    }
  }
  return { version: 1.1, tags };
}

function buildTagMap(root: string, manifest: CemPackage): string {
  const imports: string[] = [];
  const entries: string[] = [];
  let i = 0;
  for (const module of manifest.modules) {
    for (const declaration of module.declarations ?? []) {
      if (!declaration.tagName || !module.path) continue;
      const alias = `El${i++}`;
      const rel = `../../${module.path.replace(/^src\//, '')}`;
      imports.push(`import type ${alias} from '${rel}';`);
      entries.push(`    '${declaration.tagName}': ${alias};`);
    }
  }
  return `/* Generated by Lithono. Do not edit. */
${imports.join('\n')}

declare global {
  interface HTMLElementTagNameMap {
${entries.join('\n')}
  }
}

export {};
`;
}

function writeIfChanged(file: string, contents: string): boolean {
  try {
    if (readFileSync(file, 'utf8') === contents) return false;
  } catch {
    mkdirSync(dirname(file), { recursive: true });
  }
  writeFileSync(file, contents);
  return true;
}

/** Writes CEM + VS Code HTML custom data so editors can resolve custom element tags. */
export function writeEditorMetadata(root: string): string[] {
  const manifest = buildCustomElementsManifest(root);
  const htmlData = buildVscodeHtmlData(manifest);
  const written: string[] = [];
  if (writeIfChanged(join(root, MANIFEST_FILE), `${JSON.stringify(manifest, null, 2)}\n`)) {
    written.push(MANIFEST_FILE);
  }
  if (writeIfChanged(join(root, HTML_DATA_FILE), `${JSON.stringify(htmlData, null, 2)}\n`)) {
    written.push(HTML_DATA_FILE);
  }
  const tagMap = buildTagMap(root, manifest);
  if (writeIfChanged(join(root, TAG_MAP_FILE), tagMap)) {
    written.push(TAG_MAP_FILE);
  }
  return written;
}

export function isElementSourceFile(file: string): boolean {
  const posix = file.replaceAll('\\', '/');
  if (!posix.endsWith('.ts') || posix.endsWith('.d.ts')) return false;
  return (
    posix.includes('/src/components/') ||
    posix.includes('/src/framework/animate/elements/')
  );
}

function isDirectRun(): boolean {
  const entry = process.argv[1];
  if (!entry) return false;
  return fileURLToPath(import.meta.url) === resolve(entry);
}

if (isDirectRun()) {
  const written = writeEditorMetadata(process.cwd());
  console.log(
    written.length
      ? `Updated editor metadata: ${written.join(', ')}`
      : 'Editor metadata is already up to date'
  );
}
