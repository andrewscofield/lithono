import { test, expect, type Page } from '@playwright/test';
import { createHmac } from 'node:crypto';
async function signup(page: Page, name: string) {
  await page.goto('/register?next=/workshops/native-forms');
  await page.getByLabel('Name', { exact: true }).fill(name);
  await page.getByLabel('Email', { exact: true }).fill(`${name}@example.test`);
  await page.getByLabel('Password', { exact: true }).fill('workshop-password-123');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page).toHaveURL(/\/workshops\/native-forms$/);
  await expect(page.locator('input[name="token"]')).toHaveValue(/[a-f0-9-]{36}/);
}
for (const native of [true, false]) test(`workshops ${native ? 'native' : 'enhanced'} free booking validation, persisted status and email retry`, async ({ browser }) => {
  const context = await browser.newContext({ javaScriptEnabled: !native });
  const page = await context.newPage();
  await page.goto('http://127.0.0.1:4197/workshops');
  await page.getByRole('link', { name: 'Native forms workshop' }).click();
  await expect(page.getByText('Sign in to book')).toBeVisible();
  await signup(page, native ? 'workshop-native' : 'workshop-enhanced');
  if (!native) await expect(page.locator('[defer-hydration]')).toHaveCount(0);
  await page.locator('main form').evaluate(form => form.setAttribute('novalidate', ''));
  await page.getByLabel('Attendees').fill('0');
  await page.getByRole('button', { name: 'Book free places' }).click();
  await expect(page.locator('[data-error-for="quantity"]')).toBeVisible();
  await expect(page.getByLabel('Attendees')).toHaveValue('0');
  await page.getByLabel('Attendees').fill('1');
  await page.getByRole('button', { name: 'Book free places' }).click();
  await expect(page).toHaveURL(/\/workshops\/bookings\//);
  await expect(page.getByRole('status')).toHaveText('confirmed');
  await expect(page.getByText(native ? /confirmation email was accepted by Resend/ : /confirmation email could not be sent/)).toBeVisible();
  await expect(page.getByRole('region', { name: 'Booking confirmation' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Retry confirmation email' })).toHaveCount(0);
  await expect(page.getByRole('status')).toHaveText('confirmed');
  await page.reload();
  await expect(page.getByRole('status')).toHaveText('confirmed');
  await context.close();
});
test('native paid redirect and Checkout failure persist released status; another user cannot access booking', async ({ browser }) => {
  const context = await browser.newContext({ javaScriptEnabled: false });
  const page = await context.newPage();
  await signup(page, 'workshop-checkout-fail');
  await page.goto('/workshops/component-lab');
  await page.getByRole('button', { name: 'Continue to test Checkout' }).click();
  await expect(page).toHaveURL(/\/workshops\/bookings\//);
  await expect(page.getByRole('status')).toHaveText('cancelled');
  const failurePath = new URL(page.url()).pathname;
  await page.reload(); await expect(page.getByRole('status')).toHaveText('cancelled');
  const other = await browser.newContext({ javaScriptEnabled: false });
  const otherPage = await other.newPage();
  await signup(otherPage, 'workshop-native-paid');
  expect((await otherPage.request.get(failurePath)).status()).toBe(404);
  await otherPage.goto('/workshops/component-lab');
  await otherPage.route('https://checkout.stripe.com/**', route => route.fulfill({ contentType: 'text/html', body: '<p>Test transport only; no payment made.</p>' }));
  await otherPage.getByRole('button', { name: 'Continue to test Checkout' }).click();
  await expect(otherPage).toHaveURL(/checkout\.stripe\.com/);
  const id = new URL(otherPage.url()).pathname.split('/').pop()!;
  await otherPage.goto(`/workshops/bookings/${id}`);
  await expect(otherPage.getByRole('status')).toHaveText('pending');
  await other.close(); await context.close();
});
test('paid test fixture return remains pending; signed webhook confirms once; ownership and cancellation', async ({ page, request, browser }) => {
  await signup(page, 'workshop-paid');
  await page.goto('/workshops/component-lab');
  await page.route('https://checkout.stripe.com/**', route => route.fulfill({ contentType: 'text/html', body: '<h1>Server-only deterministic Checkout transport fixture</h1><p>No provider payment was made.</p>' }));
  await page.getByRole('button', { name: 'Continue to test Checkout' }).click();
  await expect(page).toHaveURL(/checkout\.stripe\.com/);
  const id = new URL(page.url()).pathname.split('/').pop()!;
  const path = `/workshops/bookings/${id}`;
  await page.goto(path + '?paid=true&session_id=untrusted');
  await expect(page.getByRole('status')).toHaveText('pending');
  const anonymous = await browser.newContext();
  expect((await anonymous.request.get(path, { maxRedirects: 0 })).status()).toBe(303);
  await anonymous.close();
  const raw = JSON.stringify({ id: `evt_${id}`, type: 'checkout.session.completed', livemode: false, data: { object: { id: `cs_test_${id}`, livemode: false, amount_total: 2500, currency: 'gbp', payment_status: 'paid', metadata: { bookingId: id } } } });
  const t = String(Math.floor(Date.now() / 1000));
  const sig = createHmac('sha256', 'whsec_local_fixture').update(`${t}.${raw}`).digest('hex');
  const options = { data: raw, headers: { 'stripe-signature': `t=${t},v1=${sig}`, 'Content-Type': 'application/json' } };
  expect((await request.post('/integrations/stripe/webhook', options)).status()).toBe(200);
  expect((await request.post('/integrations/stripe/webhook', options)).status()).toBe(200);
  await page.reload(); await expect(page.getByRole('status')).toHaveText('confirmed');
  await page.goto('/workshops/component-lab');
  await page.getByRole('button', { name: 'Continue to test Checkout' }).click();
  await expect(page).toHaveURL(/checkout\.stripe\.com/);
  const cancelId = new URL(page.url()).pathname.split('/').pop()!;
  await page.goto(`/workshops/bookings/${cancelId}?cancel=1`);
  await expect(page.getByRole('status')).toHaveText('pending');
  await page.getByRole('button', { name: 'Cancel booking and release places' }).click();
  await expect(page.getByRole('status')).toHaveText('cancelled');
});
